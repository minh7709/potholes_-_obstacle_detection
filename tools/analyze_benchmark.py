"""Benchmark Analysis Tool for Road Obstacle & FCW Live Demo.

Reads CSV telemetry generated by `tools/live.py --benchmark`, calculates key
statistical metrics (FPS, p50/p95 latency, module breakdown), and optionally
exports LaTeX tables and publication-ready charts.

Usage:
    python tools/analyze_benchmark.py
    python tools/analyze_benchmark.py --csv runs/live_benchmark_*.csv
    python tools/analyze_benchmark.py --plot
"""

import argparse
import glob
import os
import sys
from pathlib import Path

# Ensure UTF-8 output on Windows terminal
if sys.platform == "win32":
    try:
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stderr.reconfigure(encoding="utf-8")
    except Exception:
        pass

import numpy as np
import pandas as pd


def parse_args():
    parser = argparse.ArgumentParser(
        description="Analyze benchmark CSV files and generate summary reports & plots."
    )
    parser.add_argument(
        "--csv", type=str, default="",
        help="Path to specific benchmark CSV file. If not provided, uses newest in runs/."
    )
    parser.add_argument(
        "--plot", action="store_true",
        help="Generate publication-ready figures in runs/plots/."
    )
    parser.add_argument(
        "--output-dir", type=str, default="runs/plots",
        help="Directory to save generated charts (default: runs/plots)."
    )
    return parser.parse_args()


def find_latest_csv(search_dir="runs"):
    files = glob.glob(os.path.join(search_dir, "live_benchmark_*.csv"))
    if not files:
        return None
    files.sort(key=os.path.getmtime, reverse=True)
    return files[0]


def analyze_csv(filepath):
    print(f"\n=======================================================")
    print(f" ANALYZING BENCHMARK: {filepath}")
    print(f"=======================================================")

    df = pd.read_csv(filepath)
    if df.empty:
        print("[WARN] CSV file is empty.")
        return None

    # Convert numeric columns
    numeric_cols = [
        "pipeline_ms", "yolo_ms", "depth_ms", "loop_fps",
        "primary_distance_m", "primary_ttc_s", "detections", "tracks"
    ]
    for col in numeric_cols:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors="coerce")

    # Time & Frame metrics
    total_frames = len(df)
    first_ts = df["timestamp"].iloc[0] if "timestamp" in df.columns else 0
    last_ts = df["timestamp"].iloc[-1] if "timestamp" in df.columns else 0
    elapsed_sec = max(0.001, last_ts - first_ts)
    overall_fps = total_frames / elapsed_sec if elapsed_sec > 0.05 else 0.0

    # Frame dimensions
    src_res = f"{int(df['src_w'].iloc[0])}x{int(df['src_h'].iloc[0])}" if "src_w" in df.columns else "N/A"
    proc_res = f"{int(df['proc_w'].iloc[0])}x{int(df['proc_h'].iloc[0])}" if "proc_w" in df.columns else "N/A"

    # Latencies
    p_pipe = df["pipeline_ms"].dropna()
    p50_pipe = np.percentile(p_pipe, 50) if len(p_pipe) else 0.0
    p95_pipe = np.percentile(p_pipe, 95) if len(p_pipe) else 0.0
    mean_pipe = p_pipe.mean() if len(p_pipe) else 0.0

    mean_yolo = df["yolo_ms"].dropna().mean() if "yolo_ms" in df.columns else 0.0
    depth_series = df["depth_ms"].dropna()
    depth_series = depth_series[depth_series > 0]
    mean_depth = depth_series.mean() if len(depth_series) else 0.0

    mean_loop_fps = df["loop_fps"].dropna().mean() if "loop_fps" in df.columns else 0.0

    # Risk state counts
    level_counts = df["level"].value_counts().to_dict() if "level" in df.columns else {}

    # ── Video Input Obstacle Analytics ──────────────────────────────────
    # 1. Total detections & tracks on video
    total_det = int(df["detections"].sum()) if "detections" in df.columns else 0
    mean_det_per_frame = round(df["detections"].mean(), 2) if "detections" in df.columns else 0.0

    # 2. Obstacle classes detected on video input
    primary_classes = {}
    if "primary_class" in df.columns:
        pc_series = df["primary_class"].dropna()
        pc_series = pc_series[pc_series.astype(str).str.strip() != ""]
        primary_classes = pc_series.value_counts().to_dict()

    # 3. Kinematics on video input (Distance & TTC)
    dist_series = df["primary_distance_m"].dropna() if "primary_distance_m" in df.columns else pd.Series(dtype=float)
    min_dist = round(dist_series.min(), 2) if not dist_series.empty else None
    mean_dist = round(dist_series.mean(), 2) if not dist_series.empty else None

    ttc_series = df["primary_ttc_s"].dropna() if "primary_ttc_s" in df.columns else pd.Series(dtype=float)
    min_ttc = round(ttc_series.min(), 2) if not ttc_series.empty else None
    mean_ttc = round(ttc_series.mean(), 2) if not ttc_series.empty else None

    # 4. Identification of contiguous Warning / Danger Events on video
    warning_events = []
    if "level" in df.columns and "timestamp" in df.columns:
        in_event = False
        cur_event = {}
        for idx, row in df.iterrows():
            lvl = str(row.get("level", "NORMAL"))
            ts = row.get("timestamp", 0)
            frm = row.get("frame", idx)
            cls_name = row.get("primary_class", "unknown")
            dist = row.get("primary_distance_m")
            ttc = row.get("primary_ttc_s")

            if lvl in ("WARNING", "DANGER"):
                rel_sec = round(ts - first_ts, 2)
                if not in_event:
                    in_event = True
                    cur_event = {
                        "start_frame": frm,
                        "start_sec": rel_sec,
                        "end_frame": frm,
                        "end_sec": rel_sec,
                        "highest_level": lvl,
                        "classes": {cls_name} if cls_name else set(),
                        "min_distance": dist if pd.notnull(dist) else 999.0,
                        "min_ttc": ttc if pd.notnull(ttc) else 999.0,
                        "frame_count": 1,
                    }
                else:
                    cur_event["end_frame"] = frm
                    cur_event["end_sec"] = rel_sec
                    cur_event["frame_count"] += 1
                    if cls_name:
                        cur_event["classes"].add(cls_name)
                    if lvl == "DANGER":
                        cur_event["highest_level"] = "DANGER"
                    if pd.notnull(dist) and dist < cur_event["min_distance"]:
                        cur_event["min_distance"] = dist
                    if pd.notnull(ttc) and ttc < cur_event["min_ttc"]:
                        cur_event["min_ttc"] = ttc
            else:
                if in_event:
                    in_event = False
                    if cur_event["min_distance"] == 999.0:
                        cur_event["min_distance"] = None
                    if cur_event["min_ttc"] == 999.0:
                        cur_event["min_ttc"] = None
                    warning_events.append(cur_event)
                    cur_event = {}

        if in_event and cur_event:
            if cur_event["min_distance"] == 999.0:
                cur_event["min_distance"] = None
            if cur_event["min_ttc"] == 999.0:
                cur_event["min_ttc"] = None
            warning_events.append(cur_event)

    summary = {
        "file": filepath,
        "frames": total_frames,
        "elapsed_sec": round(elapsed_sec, 2),
        "src_res": src_res,
        "proc_res": proc_res,
        "overall_fps": round(overall_fps, 1),
        "mean_loop_fps": round(mean_loop_fps, 1),
        "mean_pipe_ms": round(mean_pipe, 1),
        "p50_pipe_ms": round(p50_pipe, 1),
        "p95_pipe_ms": round(p95_pipe, 1),
        "mean_yolo_ms": round(mean_yolo, 1),
        "mean_depth_ms": round(mean_depth, 1),
        "level_counts": level_counts,
        "total_detections": total_det,
        "mean_det_per_frame": mean_det_per_frame,
        "primary_classes": primary_classes,
        "min_dist": min_dist,
        "mean_dist": mean_dist,
        "min_ttc": min_ttc,
        "mean_ttc": mean_ttc,
        "warning_events": warning_events,
        "df": df,
    }

    print(f"\n[1. SYSTEM & RUNTIME BENCHMARK]")
    print(f"Frames processed : {summary['frames']}")
    print(f"Elapsed time     : {summary['elapsed_sec']} s")
    print(f"Resolution       : Source {summary['src_res']} -> Processing {summary['proc_res']}")
    print(f"Throughput       : {summary['overall_fps']} FPS (Sliding Avg: {summary['mean_loop_fps']} FPS)")
    print(f"Pipeline Latency : Mean={summary['mean_pipe_ms']}ms | P50={summary['p50_pipe_ms']}ms | P95={summary['p95_pipe_ms']}ms")
    print(f"Module Breakdown : YOLO11n={summary['mean_yolo_ms']}ms | Depth={summary['mean_depth_ms']}ms")

    print(f"\n[2. VIDEO INPUT & OBSTACLE ANALYTICS]")
    print(f"Total Detections : {summary['total_detections']} (Avg {summary['mean_det_per_frame']} boxes/frame)")
    print(f"Detected Classes : {summary['primary_classes'] if summary['primary_classes'] else 'No objects in primary corridor'}")
    dist_str = f"Min={summary['min_dist']}m | Mean={summary['mean_dist']}m" if summary['min_dist'] is not None else "No distance measured"
    ttc_str = f"Min={summary['min_ttc']}s | Mean={summary['mean_ttc']}s" if summary['min_ttc'] is not None else "No TTC measured"
    print(f"Distance Stats   : {dist_str}")
    print(f"TTC Stats        : {ttc_str}")
    print(f"Risk States      : {summary['level_counts']}")
    print(f"Warning Events   : {len(summary['warning_events'])} distinct event(s) detected on video")

    if summary["warning_events"]:
        print("\n  -> Timeline of Warning Events on Video:")
        for i, ev in enumerate(summary["warning_events"], 1):
            classes_str = ", ".join(ev["classes"]) if ev["classes"] else "unknown"
            dist_str = f"{ev['min_distance']:.2f}m" if ev['min_distance'] is not None else "--"
            ttc_str = f"{ev['min_ttc']:.2f}s" if ev['min_ttc'] is not None else "inf"
            print(f"     * Event #{i} [{ev['highest_level']}]: "
                  f"Time {ev['start_sec']}s -> {ev['end_sec']}s (Frames {ev['start_frame']}->{ev['end_frame']}, {ev['frame_count']} frames) | "
                  f"Class: {classes_str} | Min Dist: {dist_str} | Min TTC: {ttc_str}")

    print("-------------------------------------------------------")

    # LaTeX snippet generator for BAO_CAO_KHOA_HOC_FCW.tex Table 10
    print("\n[LaTeX Snippet for Report Table (tab:software_runtime_benchmark)]")
    print(f"% Resolution: {proc_res}")
    print(f"Thời gian YOLO11n & {summary['mean_yolo_ms']:.1f}\\text{{ ms}} \\\\")
    print(f"Thời gian Depth (nhịp chu kỳ 5) & {summary['mean_depth_ms']:.1f}\\text{{ ms}} \\\\")
    print(f"Độ trễ trung vị $P_{{50}}$ & {summary['p50_pipe_ms']:.1f}\\text{{ ms}} \\\\")
    print(f"Độ trễ xấu nhất $P_{{95}}$ & {summary['p95_pipe_ms']:.1f}\\text{{ ms}} \\\\")
    print(f"Tốc độ khung hình (FPS) & \\mathbf{{{summary['overall_fps']:.1f}\\text{{ FPS}}}} \\\\")
    print("-------------------------------------------------------\n")

    return summary


def plot_benchmark(summary, output_dir):
    import matplotlib.pyplot as plt

    os.makedirs(output_dir, exist_ok=True)
    df = summary["df"]

    # 1. Timeline Chart (FPS and Latency)
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(10, 6), sharex=True)
    fig.suptitle("Real-time Performance Timeline (Laptop CPU Demo)", fontsize=14, fontweight="bold")

    frames = df["frame"] if "frame" in df.columns else range(len(df))

    if "loop_fps" in df.columns:
        ax1.plot(frames, df["loop_fps"], color="#1f77b4", label="Sliding FPS (W=30)", linewidth=1.5)
        ax1.axhline(summary["overall_fps"], color="#ff7f0e", linestyle="--",
                    label=f"Overall Avg ({summary['overall_fps']} FPS)")
    ax1.set_ylabel("Frame Rate (FPS)", fontsize=11)
    ax1.grid(True, linestyle=":", alpha=0.6)
    ax1.legend(loc="upper right")

    if "pipeline_ms" in df.columns:
        ax2.plot(frames, df["pipeline_ms"], color="#2ca02c", label="Pipeline Latency (ms)", linewidth=1.2)
        ax2.axhline(summary["p50_pipe_ms"], color="#17becf", linestyle="--",
                    label=f"P50 ({summary['p50_pipe_ms']} ms)")
        ax2.axhline(summary["p95_pipe_ms"], color="#d62728", linestyle="--",
                    label=f"P95 ({summary['p95_pipe_ms']} ms)")
    ax2.set_xlabel("Frame Number", fontsize=11)
    ax2.set_ylabel("Latency (ms)", fontsize=11)
    ax2.grid(True, linestyle=":", alpha=0.6)
    ax2.legend(loc="upper right")

    plt.tight_layout()
    chart1_path = os.path.join(output_dir, "performance_timeline.png")
    plt.savefig(chart1_path, dpi=200)
    plt.close()
    print(f"[Exported Chart] -> {chart1_path}")

    # 2. Latency Distribution Histogram (P50 / P95)
    if "pipeline_ms" in df.columns and len(df["pipeline_ms"].dropna()) > 5:
        plt.figure(figsize=(8, 5))
        p_pipe = df["pipeline_ms"].dropna()
        plt.hist(p_pipe, bins=25, color="#3498db", edgecolor="black", alpha=0.7, density=True)
        plt.axvline(summary["p50_pipe_ms"], color="#2ecc71", linestyle="--", linewidth=2,
                    label=f"P50 Median = {summary['p50_pipe_ms']} ms")
        plt.axvline(summary["p95_pipe_ms"], color="#e74c3c", linestyle="--", linewidth=2,
                    label=f"P95 Worst-case = {summary['p95_pipe_ms']} ms")
        plt.title("Pipeline Latency Distribution (P50 vs P95)", fontsize=13, fontweight="bold")
        plt.xlabel("Processing Time per Frame (ms)", fontsize=11)
        plt.ylabel("Probability Density", fontsize=11)
        plt.grid(True, linestyle=":", alpha=0.6)
        plt.legend()
        plt.tight_layout()
        chart2_path = os.path.join(output_dir, "latency_distribution.png")
        plt.savefig(chart2_path, dpi=200)
        plt.close()
        print(f"[Exported Chart] -> {chart2_path}")

    # 3. Distance & TTC Kinematics Curve (if obstacles were tracked)
    if "primary_distance_m" in df.columns and df["primary_distance_m"].dropna().count() > 3:
        tracked = df.dropna(subset=["primary_distance_m"])
        fig, ax = plt.subplots(figsize=(9, 5))
        ax.plot(tracked["frame"], tracked["primary_distance_m"], color="#e67e22",
                marker="o", markersize=3, label="Estimated Distance (m)")
        ax.set_xlabel("Frame Number", fontsize=11)
        ax.set_ylabel("Distance to Primary Target (m)", fontsize=11, color="#e67e22")
        ax.grid(True, linestyle=":", alpha=0.6)

        if "primary_ttc_s" in tracked.columns and tracked["primary_ttc_s"].dropna().count() > 3:
            ax2 = ax.twinx()
            ax2.plot(tracked["frame"], tracked["primary_ttc_s"], color="#9b59b6",
                     linestyle="--", label="Time-to-Collision (s)")
            ax2.set_ylabel("TTC (seconds)", fontsize=11, color="#9b59b6")
            ax2.axhline(4.0, color="#f39c12", linestyle=":", label="Warning Threshold (4.0s)")
            ax2.axhline(2.0, color="#c0392b", linestyle=":", label="Danger Threshold (2.0s)")

        plt.title("Forward Obstacle Approach Kinematics (Distance & TTC)", fontsize=13, fontweight="bold")
        plt.tight_layout()
        chart3_path = os.path.join(output_dir, "kinematics_distance_ttc.png")
        plt.savefig(chart3_path, dpi=200)
        plt.close()
        print(f"[Exported Chart] -> {chart3_path}")


def main():
    args = parse_args()
    csv_path = args.csv or find_latest_csv()

    if not csv_path or not os.path.exists(csv_path):
        print("[ERROR] No benchmark CSV found. Run `python tools/live.py --benchmark` first.")
        return 1

    summary = analyze_csv(csv_path)
    if summary and args.plot:
        plot_benchmark(summary, args.output_dir)

    return 0


if __name__ == "__main__":
    sys.exit(main())
